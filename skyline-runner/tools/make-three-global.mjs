// Converts the official three.js ES-module build into a classic script that
// defines `window.THREE`. Classic scripts load from file:// URLs, so the game
// runs by simply double-clicking index.html (no server, no network).
//
//   npm i three@0.170.0
//   node tools/make-three-global.mjs node_modules/three/build/three.module.min.js lib/three.min.js
import { readFileSync, writeFileSync } from 'node:fs';

const [src, dst] = process.argv.slice(2);
let code = readFileSync(src, 'utf8');
const at = code.lastIndexOf('export{');
if (at < 0) throw new Error('export block not found');
const end = code.indexOf('}', at);
const names = code.slice(at + 7, end).split(',').map((s) => {
  const [local, exported] = s.trim().split(/\s+as\s+/);
  return `${exported || local}:${local}`;
});
if (/\bimport\s*[{*]/.test(code.slice(0, at))) throw new Error('build has imports');
const license = code.match(/^\/\*\*[\s\S]*?\*\//)[0];
code = code.slice(license.length, at) + code.slice(end + 1).replace(/^;/, '');
writeFileSync(dst, `${license}\n// Classic-script wrapper generated by tools/make-three-global.mjs\n(function(){${code}\nwindow.THREE=Object.freeze({${names.join(',')}});})();\n`);
console.log(`wrote ${dst} with ${names.length} exports`);
